create table if not exists public.historial_estado_pedido (
  id bigint generated by default as identity primary key,
  id_pedido bigint not null references public.pedido(id) on delete cascade,
  id_usuario_responsable bigint references public.usuario(id) on delete set null,
  estado text,
  observacion text,
  fecha_cambio timestamptz not null default now()
);
create index if not exists historial_id_pedido_idx on public.historial_estado_pedido (id_pedido);
create index if not exists historial_id_usuario_idx on public.historial_estado_pedido (id_usuario_responsable);
