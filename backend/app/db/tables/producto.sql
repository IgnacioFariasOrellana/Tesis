create table if not exists public.producto (
  id bigint generated by default as identity primary key,
  id_categoria bigint not null references public.categoria(id) on delete restrict,
  nombre text not null,
  descripcion text not null,
  precio numeric(12,2) not null check (precio >= 0),
  imagen_url text,
  disponible boolean not null default true,
  activo boolean not null default true,
  slug text not null unique,
  etiqueta text not null default '',
  ocasiones jsonb not null default '[]'::jsonb,
  caracteristicas jsonb not null default '[]'::jsonb,
  disponible_hoy boolean not null default false,
  constraint producto_occasiones_lista check (jsonb_typeof(ocasiones) = 'array'),
  constraint producto_caracteristicas_lista check (jsonb_typeof(caracteristicas) = 'array')
);
create index if not exists producto_id_categoria_idx on public.producto (id_categoria);
