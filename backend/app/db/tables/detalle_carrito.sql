create table if not exists public.detalle_carrito (
  id bigint generated by default as identity primary key,
  id_carrito bigint not null references public.carrito(id) on delete cascade,
  id_producto bigint not null references public.producto(id) on delete restrict,
  cantidad integer not null check (cantidad > 0),
  precio_unitario numeric(12,2) not null check (precio_unitario >= 0)
);
create index if not exists detalle_carrito_id_carrito_idx on public.detalle_carrito (id_carrito);
create index if not exists detalle_carrito_id_producto_idx on public.detalle_carrito (id_producto);
