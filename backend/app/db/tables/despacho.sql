create table if not exists public.despacho (
  id bigint generated by default as identity primary key,
  id_pedido bigint not null unique references public.pedido(id) on delete restrict,
  id_ruta bigint references public.ruta_reparto(id) on delete set null,
  orden_sugerido integer,
  orden_final integer,
  estado text,
  hora_salida timestamptz,
  hora_entrega timestamptz,
  constraint despacho_horas check (hora_entrega is null or hora_salida is null or hora_entrega >= hora_salida)
);
create index if not exists despacho_id_ruta_idx on public.despacho (id_ruta);
