create table if not exists public.detalle_pedido (
  id bigint generated by default as identity primary key,
  id_pedido bigint not null references public.pedido(id) on delete cascade,
  id_producto bigint not null references public.producto(id) on delete restrict,
  nombre_producto text,
  cantidad integer not null check (cantidad > 0),
  precio_unitario numeric(12,2) not null check (precio_unitario >= 0),
  subtotal numeric(12,2) not null check (subtotal >= 0)
);
create index if not exists detalle_pedido_id_pedido_idx on public.detalle_pedido (id_pedido);
create index if not exists detalle_pedido_id_producto_idx on public.detalle_pedido (id_producto);
