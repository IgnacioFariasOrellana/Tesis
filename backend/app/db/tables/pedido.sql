create table if not exists public.pedido (
  id bigint generated by default as identity primary key,
  id_usuario bigint references public.usuario(id) on delete set null,
  numero_pedido text unique,
  checkout_token uuid unique,
  estado_actual text,
  subtotal numeric(12,2) not null check (subtotal >= 0),
  costo_entrega numeric(12,2) not null check (costo_entrega >= 0),
  total numeric(12,2) not null check (total >= 0),
  fecha_creacion timestamptz not null default now(),
  fecha_actualizacion timestamptz not null default now()
);
create index if not exists pedido_id_usuario_idx on public.pedido (id_usuario);
