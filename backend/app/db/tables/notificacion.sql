create table if not exists public.notificacion (
  id bigint generated by default as identity primary key,
  id_usuario bigint not null references public.usuario(id) on delete cascade,
  id_pedido bigint references public.pedido(id) on delete set null,
  tipo text,
  mensaje text,
  estado text,
  fecha_envio timestamptz,
  fecha_lectura timestamptz,
  fecha_creacion timestamptz not null default now()
);
create index if not exists notificacion_id_usuario_idx on public.notificacion (id_usuario);
create index if not exists notificacion_id_pedido_idx on public.notificacion (id_pedido);
