create table if not exists public.carrito (
  id bigint generated by default as identity primary key,
  id_usuario bigint references public.usuario(id) on delete restrict,
  token_sesion text,
  estado text,
  fecha_creacion timestamptz not null default now(),
  fecha_actualizacion timestamptz not null default now(),
  fecha_expiracion timestamptz,
  constraint carrito_propietario check (id_usuario is not null or token_sesion is not null)
);
create index if not exists carrito_id_usuario_idx on public.carrito (id_usuario);
create index if not exists carrito_token_sesion_idx on public.carrito (token_sesion);
