create table if not exists public.aceptacion_politica_privacidad (
  id bigint generated by default as identity primary key,
  id_usuario bigint not null references public.usuario(id) on delete restrict,
  version_politica text,
  medio_aceptacion text,
  fecha_aceptacion timestamptz not null default now()
);
create index if not exists aceptacion_id_usuario_idx on public.aceptacion_politica_privacidad (id_usuario);
