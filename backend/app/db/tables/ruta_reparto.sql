create table if not exists public.ruta_reparto (
  id bigint generated by default as identity primary key,
  id_repartidor bigint not null references public.usuario(id) on delete restrict,
  fecha_reparto date not null,
  estado text
);
create index if not exists ruta_reparto_id_repartidor_idx on public.ruta_reparto (id_repartidor);
