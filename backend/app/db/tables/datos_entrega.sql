create table if not exists public.datos_entrega (
  id bigint generated by default as identity primary key,
  id_pedido bigint not null unique references public.pedido(id) on delete cascade,
  nombre_destinatario text,
  telefono_destinatario text,
  fecha_entrega date not null,
  hora_desde time not null,
  hora_hasta time not null,
  direccion text,
  referencia_direccion text,
  latitud numeric(9,6),
  longitud numeric(9,6),
  dedicatoria text,
  instrucciones text,
  constraint datos_entrega_horario check (hora_hasta > hora_desde),
  constraint datos_entrega_latitud check (latitud between -90 and 90),
  constraint datos_entrega_longitud check (longitud between -180 and 180)
);
